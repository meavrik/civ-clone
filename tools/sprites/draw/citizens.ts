/** A layer's pixels over the base from row `top` down; clear pixels leave the base. */
function over(base: string[], layer: string[], top = 0): string[] {
  const out = base.map((r) => [...r]);
  layer.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== ".") out[top + y]![x] = ch; }));
  return out.map((r) => r.join(""));
}

type Mood = "happy" | "content" | "unhappy" | "entertainer" | "taxman" | "scientist";
const MOODS: Mood[] = ["happy", "content", "unhappy", "entertainer", "taxman", "scientist"];

function figure(mood: Mood, head: string, woman: boolean): string[] {
  const upper = mood === "happy" ? "up" : mood === "unhappy" ? "crossed" : "down";
  let g = Array.from({ length: H }, () => ".".repeat(W));
  g = over(g, UPPER[upper]!, 6);
  g = over(g, LOWER[woman ? "dress" : "trousers"]!, 15);
  if (upper === "up") g = over(g, RAISED, 0);
  g = over(g, HEADS[head]!);
  if (mood === "entertainer") g = over(over(g, JESTER, 0), LUTE, 7);
  if (mood === "taxman") g = over(over(g, BOWLER, 0), PURSE, 13);
  if (mood === "scientist") g = over(woman ? g : over(g, COAT, 15), FLASK, 10);
  return g;
}

