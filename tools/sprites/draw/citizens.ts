// Draws the citizens sheet (the city screen's people): one figure, as plain as a person can be drawn,
// a round head over a body and two legs (asked for 2026-10-24, after three rounds of detailed people:
// "do the most simple basic human presentation possible - dont over complicate"). Everyone is this
// figure; citizens.ts colours the head with the person's skin and the body with the mood or trade.
// Run from the repo root: npx vite-node --script tools/sprites/draw/citizens.ts
// Rewrites packages/renderer-retro/src/art/citizens.art.ts; the art text stays the source the game reads.
// Legend: skin 6/4/2 (lit, shade, outline), clothes P/p/r (lit, shade, outline), swapped per person.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const W = 16;

/** The figure, 16 wide and 26 tall: a head, a gap for the neck, a body as wide as its arms, two legs. */
const PERSON = `
................
......2222......
.....266642.....
.....266642.....
.....266642.....
.....266642.....
......2222......
................
.....rrrrrr.....
....rPPPPppr....
...rPPPPPpppr...
...rPPPPPpppr...
...rPPPPPpppr...
...rPPPPPpppr...
...rPPPPPpppr...
...rPPPPPpppr...
....rPPPPppr....
....rPPrrppr....
....rPPrrppr....
....rPPrrppr....
....rPPrrppr....
....rPPrrppr....
....rPPrrppr....
....rPPrrppr....
....rrrrrrrr....
................
`.trim().split("\n");

for (const r of PERSON) if (r.length !== W) throw new Error(`a row of ${r.length}, not ${W}: ${r}`);

const HEADER = [
  "// citizens sprites for the retro renderer. Edit the grids by hand, or export/import a PNG with `npm run sprites`.",
  "// Every character must be in the legend described in the comment lines below.",
  "export default String.raw`",
  "# Citizens, 32x32: two pixels to each screen pixel. One figure for everyone, as plain as a person can be",
  "# drawn (asked for 2026-10-24: \"do the most simple basic human presentation possible\"): a round head",
  "# over a body and two legs, 16 wide and 26 tall in the sprite's left half. citizens.ts colours the head",
  "# with each person's skin and the body with the mood (yellow happy, white content, red unhappy) or the",
  "# trade (magenta entertainer, orange taxman, cyan scientist).",
  "# Legend: . clear   skin 6/4/2 (lit, shade, outline; ramp flesh)   clothes P/p/r (owner, owner dark, red)",
  "# Drawn by tools/sprites/draw/citizens.ts; change the figure there and run it.",
].join("\n");

const rows = [...PERSON, ...Array.from({ length: 32 - PERSON.length }, () => ".".repeat(W))].map((r) => r + ".".repeat(W));
const root = resolve(fileURLToPath(import.meta.url), "../../../..");
writeFileSync(resolve(root, "packages/renderer-retro/src/art/citizens.art.ts"), `${HEADER}\n\n@person\n${rows.join("\n")}\n\`;\n`);
