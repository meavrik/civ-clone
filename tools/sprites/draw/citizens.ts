/** A layer's pixels over the base from row `top` down; clear pixels leave the base. */
function over(base: string[], layer: string[], top = 0): string[] {
  const out = base.map((r) => [...r]);
  layer.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== ".") out[top + y]![x] = ch; }));
  return out.map((r) => r.join(""));
}

type Mood = "happy" | "content" | "unhappy" | "entertainer" | "taxman" | "scientist";
const MOODS: Mood[] = ["happy", "content", "unhappy", "entertainer", "taxman", "scientist"];
/** The mouth's two rows (upper, lower): a smile, a straight mouth, a frown. */
const SMILE = ["262", "624"];
const PLAIN = ["664", "624"];
const FROWN = ["624", "262"];
const MOUTH: Record<Mood, string[]> = { happy: SMILE, content: PLAIN, unhappy: FROWN, entertainer: SMILE, taxman: PLAIN, scientist: PLAIN };

function figure(mood: Mood, head: string, woman: boolean): string[] {
  const upper = mood === "happy" ? "up" : mood === "unhappy" ? "crossed" : "down";
  let g = Array.from({ length: H }, () => ".".repeat(W));
  g = over(g, UPPER[upper]!, 9);
  g = over(g, LOWER[woman ? "dress" : "trousers"]!, 17);
  if (upper === "up") g = over(g, RAISED, 3);
  const [u, v, x] = [...MOUTH[mood][0]!];
  const [l, m, r] = [...MOUTH[mood][1]!];
  const face = HEADS[head]!.map((row) =>
    row.replace("U", u!).replace("V", v!).replace("X", x!).replace("L", l!).replace("M", m!).replace("R", r!).replaceAll("q", mood === "unhappy" ? "a" : "6"),
  );
  g = over(g, face);
  if (mood === "entertainer") g = over(g, JESTER);
  if (mood === "taxman") g = over(over(g, BOWLER), PURSE, 16);
  if (mood === "scientist") g = over(over(g, GLASSES, 5), FLASK, 16);
  return g;
}

